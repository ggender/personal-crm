// Creates .env with freshly generated secrets, or adds the lines a newer version of the app needs
// to an existing .env. Existing lines are never changed, and no value is ever printed.
// The file is .env in the current folder; ENV_FILE points to another one (used by the checks).
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const envPath = resolve(process.cwd(), process.env.ENV_FILE || ".env");
const secret = (bytes) => randomBytes(bytes).toString("hex");
const port = 5433;

// Which keys the file has already, and their values (needed only to reuse the database password).
function readEnv(path) {
  const values = new Map();
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const match = /^\s*([A-Z][A-Z0-9_]*)=(.*)$/.exec(line);
    if (match) values.set(match[1], match[2].trim());
  }
  return values;
}

// Every setting of the app, in file order. A blank line before a group, a comment above it.
// `value` is computed from what is already in the file, so a database password is never replaced.
function settings(existing) {
  const password = existing.get("POSTGRES_PASSWORD") || secret(24);
  return [
    { key: "POSTGRES_PASSWORD", value: password },
    { key: "POSTGRES_PORT", value: String(port) },
    {
      key: "DATABASE_URL",
      value: `postgres://crm:${password}@localhost:${existing.get("POSTGRES_PORT") || port}/crm`,
    },
    {
      comment: "Signs the login cookies. Random, never shared.",
      key: "BETTER_AUTH_SECRET",
      value: secret(32),
    },
    {
      comment: "Address of the app on this computer: login links in the emails point to it.",
      key: "BETTER_AUTH_URL",
      value: "http://localhost:3000",
    },
    {
      comment: "Where emails go: Mailpit from docker-compose.yml, page with the emails: :8025.",
      key: "SMTP_URL",
      value: "smtp://127.0.0.1:1025",
    },
    {
      comment: "The sender of the login emails.",
      key: "MAIL_FROM",
      value: '"Личная CRM <noreply@mail.crm.vprodcrm.ru>"',
    },
    {
      comment: "Your email: the contacts that already exist and the demo data belong to it.",
      key: "OWNER_EMAIL",
      value: "",
    },
  ];
}

const created = !existsSync(envPath);
const existing = created ? new Map() : readEnv(envPath);
const missing = settings(existing).filter(({ key }) => !existing.has(key));

if (missing.length === 0) {
  console.log(`${envPath} already has every setting - left unchanged.`);
} else {
  const lines = missing.flatMap(({ comment, key, value }) => [
    ...(comment ? ["", `# ${comment}`] : []),
    `${key}=${value}`,
  ]);
  if (created) {
    const header = "# Generated by pnpm env:init. Do not commit this file.";
    writeFileSync(envPath, [header, ...lines, ""].join("\n"), { mode: 0o600 });
  } else {
    const text = readFileSync(envPath, "utf8");
    appendFileSync(envPath, `${text.endsWith("\n") ? "" : "\n"}${lines.join("\n")}\n`);
  }
  console.log(
    `${created ? "Created" : "Updated"} ${envPath}. Added: ${missing.map(({ key }) => key).join(", ")} (values not shown).`,
  );
}

// An empty OWNER_EMAIL would stop the migration, so say it out loud every time.
const ownerEmail = missing.find(({ key }) => key === "OWNER_EMAIL")
  ? ""
  : (existing.get("OWNER_EMAIL") ?? "");
if (!ownerEmail.replace(/^["']|["']$/g, "")) {
  console.log("Next step: write your email after OWNER_EMAIL= in the file (do it yourself).");
}
